import 'dotenv/config';
import * as lark from '@larksuiteoapi/node-sdk';
import path from 'node:path';
import {Store, Queue, handler} from './core.mjs';
import {execute} from './agent.mjs';
const appId=process.env.FEISHU_APP_ID;
const appSecret=process.env.FEISHU_APP_SECRET;
const allowed=new Set((process.env.FEISHU_ALLOWED_OPEN_IDS||'').split(',').map(x=>x.trim()).filter(Boolean));
if(!appId||!appSecret||allowed.size===0)throw new Error('Missing Feishu app credentials or allowed IDs');
const client=new lark.Client({appId,appSecret,domain:lark.Domain.Feishu});
const store=new Store(path.resolve('data/jobs.sqlite'));
const checked=async request=>{const result=await request;if(result?.code!==0)throw Error('Feishu message delivery failed');return result};
const reply=(id,text)=>checked(client.im.message.reply({path:{message_id:id},data:{msg_type:'text',content:JSON.stringify({text})}}));
const notify=(task,text)=>checked(client.im.message.create({params:{receive_id_type:'chat_id'},data:{receive_id:task.chat_id,msg_type:'text',content:JSON.stringify({text})}}));
const queue=new Queue(store,execute,notify,{reply});
const dispatcher=new lark.EventDispatcher({}).register({'im.message.receive_v1':handler({store,queue,reply,allowed})});
const ws=new lark.WSClient({appId,appSecret,domain:lark.Domain.Feishu});
await ws.start({eventDispatcher:dispatcher});
console.log('Feishu AI Employee ready');
